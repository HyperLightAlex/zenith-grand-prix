"""Build the mechs' painted panel lines and markings (the anime look) from
the sheets in art/mech-sheets.

    python3 tools/bg/build_mech.py

Writes src/client/render/mech/art/* and a generated module
src/client/render/mech/mechArt.ts that the mechs import. Run it again after
replacing a sheet.

What it does to the sheets:
- Panel lines (P1): each square cut just inside the lines drawn between
  them, turned into a mask (1 where there is ink), and packed three to a
  texture, one to a colour channel. The squares do not repeat on their own
  (line drawings seldom do), so the game repeats them mirrored, which always
  joins: a seam that reaches an edge carries on as its own reflection.
- Markings (P2): each cut out of the green by its own outline (grouped by
  the cell of the 4x3 grid its middle falls in) and kept at its own shape.
"""
import json
import os

import numpy as np
from PIL import Image
from scipy import ndimage

from build_backgrounds import save
from build_hud import pieces

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
SHEETS = os.path.join(ROOT, 'art', 'mech-sheets')
OUT = os.path.join(ROOT, 'src', 'client', 'render', 'mech')

# P1, in sheet order; packed A = (plates, panels, limbs), B = (frame, dark, wear).
PANELS = ['plates', 'panels', 'limbs', 'frame', 'dark', 'wear']
MARKS = ['caution', 'warning', 'stencil', 'text', 'arrow', 'lift', 'stripes', 'chevrons', 'one', 'two', 'three', 'roundel']


def join_near(profile, at, reach=10):
    """The heaviest line of ink near `at` in a column or row profile (the grid drawn between squares)."""
    lo = at - reach
    return lo + int(np.argmax(profile[lo:at + reach]))


def panel_masks():
    a = np.asarray(Image.open(os.path.join(SHEETS, 'mech-p1-panels.png')).convert('L')).astype(np.float32) / 255
    ink = 1 - a
    cols, rows = ink.mean(0), ink.mean(1)
    xs = [0, join_near(cols, 512), join_near(cols, 1024), a.shape[1]]
    ys = [0, join_near(rows, 512), a.shape[0]]
    inset = 6
    out = []
    for i in range(6):
        r, c = divmod(i, 3)
        t = ink[ys[r] + inset:ys[r + 1] - inset, xs[c] + inset:xs[c + 1] - inset]
        # Ink to 1, paper to 0, the anti-aliased edge kept; the lines thickened
        # a little, so they still draw at the size a mech is usually seen.
        m = np.clip((t - 0.08) / 0.6, 0, 1)
        m = ndimage.grey_dilation(m, size=(3, 3))
        im = Image.fromarray((m * 255).astype(np.uint8), 'L').resize((512, 512), Image.LANCZOS)
        out.append(np.asarray(im).astype(np.float32) / 255)
    return out


def main():
    d = os.path.join(OUT, 'art')
    os.makedirs(d, exist_ok=True)
    m = panel_masks()
    a = np.stack(m[:3], -1)
    b = np.stack(m[3:], -1)
    for name, arr in (('panels-a', a), ('panels-b', b)):
        Image.fromarray((arr * 255 + 0.5).astype(np.uint8), 'RGB').save(os.path.join(d, f'{name}.webp'), 'WEBP', lossless=True)
    rgb = np.asarray(Image.open(os.path.join(SHEETS, 'mech-p2-markings.png')).convert('RGB')).astype(np.float32) / 255
    aspect = {}
    for name, p in zip(MARKS, pieces(rgb, 4, 3, 8)):
        h, w = p.shape[:2]
        s = 256 / max(h, w)
        im = Image.fromarray((np.clip(p, 0, 1) * 255).astype(np.uint8), 'RGBA').resize((max(1, round(w * s)), max(1, round(h * s))), Image.LANCZOS)
        q = np.asarray(im).astype(np.float32) / 255
        save(q, os.path.join(d, f'mark-{name}.webp'), 92)
        aspect[name] = round(w / h, 4)
    lines = [
        '// Generated by tools/bg/build_mech.py from art/mech-sheets. Do not edit by hand.',
        '// The anime look on the mechs: panel lines (masks packed three to a texture) and markings.',
        "import panelsA from './art/panels-a.webp';",
        "import panelsB from './art/panels-b.webp';",
    ]
    for name in MARKS:
        lines.append(f"import mark_{name} from './art/mark-{name}.webp';")
    lines += [
        '',
        '/** Panel-line masks: A holds plates, panels and limbs; B the frame, the dark parts and wear. */',
        'export const PANELS = { a: panelsA, b: panelsB };',
        '',
        '/** The markings, each with its width over its height. */',
        'export const MARKS = {',
        *[f'  {name}: {{ url: mark_{name}, aspect: {aspect[name]} }},' for name in MARKS],
        '} as const;',
        'export type MarkName = keyof typeof MARKS;',
        '',
    ]
    with open(os.path.join(OUT, 'mechArt.ts'), 'w') as fh:
        fh.write('\n'.join(lines))
    print('aspects', json.dumps(aspect))


if __name__ == '__main__':
    main()
