"""Build the title screen's key art (the anime look) from the images in
art/key-sheets.

    python3 tools/bg/build_key.py

Writes src/client/ui/art/cover.webp and logo.webp, and a generated module
src/client/ui/keyArt.ts that the menus and the eyecatch import. Run it again
after replacing an image.

What it does:
- Cover (K1): kept whole, at its own size.
- Logo (K2): cut out of the green by its outline and trimmed to it, a little
  clear round the edge.
"""
import os

import numpy as np
from PIL import Image

from build_backgrounds import keyed, save
from build_hud import resized

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
SHEETS = os.path.join(ROOT, 'art', 'key-sheets')
OUT = os.path.join(ROOT, 'src', 'client', 'ui')


def main():
    d = os.path.join(OUT, 'art')
    os.makedirs(d, exist_ok=True)
    cover = np.asarray(Image.open(os.path.join(SHEETS, 'key-k1-cover.png')).convert('RGB')).astype(np.float32) / 255
    kb = save(cover, os.path.join(d, 'cover.webp'), 86)
    rgb = np.asarray(Image.open(os.path.join(SHEETS, 'key-k2-logo.png')).convert('RGB')).astype(np.float32) / 255
    k = keyed(rgb)
    ys, xs = np.nonzero(k[..., 3] > 0.02)
    pad = 8
    p = k[max(0, ys.min() - pad):ys.max() + pad + 1, max(0, xs.min() - pad):xs.max() + pad + 1]
    w = 1200
    h = round(w * p.shape[0] / p.shape[1])
    lb = save(resized(p, w, h), os.path.join(d, 'logo.webp'), 92)
    aspect = round(w / h, 4)
    lines = [
        '// Generated by tools/bg/build_key.py from art/key-sheets. Do not edit by hand.',
        "// The title screen's key art for the anime look: the cover image and the logo.",
        "import cover from './art/cover.webp';",
        "import logo from './art/logo.webp';",
        '',
        '/** The cover image behind the title screen; its left 40% is open sky, for the logo and menu. */',
        'export const COVER = cover;',
        '',
        '/** ZENITH GRAND PRIX in chrome, cut out, with its width over its height. */',
        f'export const LOGO = {{ url: logo, aspect: {aspect} }};',
        '',
    ]
    with open(os.path.join(OUT, 'keyArt.ts'), 'w') as fh:
        fh.write('\n'.join(lines))
    print(f'key art: cover {kb // 1024} KB, logo {lb // 1024} KB, logo aspect {aspect}')


if __name__ == '__main__':
    main()
